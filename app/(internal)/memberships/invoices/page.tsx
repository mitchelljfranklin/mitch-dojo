import Link from "next/link";

import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { Breadcrumbs } from "@/components/breadcrumbs";
import { FlashToast } from "@/components/flash-toast";
import { Pagination } from "@/components/pagination";
import { AutoSubmitSelect } from "@/components/auto-submit-select";
import { SearchInput } from "@/components/search-input";
import { NewInvoiceSheet } from "./new-invoice-sheet";
import { requirePermission } from "@/lib/auth";
import { PERMISSIONS, hasPermission } from "@/lib/permissions";
import {
  listInvoices,
  listActivePlansForSelection,
} from "@/lib/db/memberships";
import { prisma } from "@/lib/prisma";
import { getMembershipsSettings } from "@/lib/settings";
import { formatDate, formatMoney } from "@/lib/utils";

export const dynamic = "force-dynamic";

export const metadata = { title: "Invoices" };

const STATUS_LABELS: Record<string, string> = {
  OPEN: "Open",
  PAID: "Paid",
  VOID: "Void",
};

type InvoicesPageProps = {
  searchParams: Promise<Record<string, string | undefined>>;
};

function statusBadgeVariant(status: string) {
  if (status === "PAID") return "secondary" as const;
  if (status === "VOID") return "outline" as const;
  return "default" as const;
}

export default async function InvoicesPage({
  searchParams,
}: InvoicesPageProps) {
  const user = await requirePermission(PERMISSIONS.MEMBERSHIPS_VIEW);
  const canEdit = hasPermission(user.permissions, PERMISSIONS.MEMBERSHIPS_EDIT);
  const { currency } = await getMembershipsSettings();

  const sp = await searchParams;
  const statusFilter =
    sp.status === "OPEN" || sp.status === "PAID" || sp.status === "VOID"
      ? sp.status
      : undefined;
  const overdueOnly = sp.status === "OVERDUE";
  const studentId = sp.studentId;
  const search = sp.q?.trim() ?? "";
  const page = Math.max(1, Number(sp.page ?? "1") || 1);

  const { rows, total } = await listInvoices(
    {
      status: overdueOnly ? undefined : statusFilter,
      overdueOnly,
      studentId,
      studentName: search,
    },
    page,
  );

  const [invoiceStudents, invoicePlans] = await Promise.all([
    canEdit
      ? prisma.student.findMany({
          where: { status: { in: ["ACTIVE", "TRIAL"] } },
          select: { id: true, firstName: true, lastName: true },
          orderBy: [{ lastName: "asc" }, { firstName: "asc" }],
        })
      : Promise.resolve([]),
    canEdit ? listActivePlansForSelection() : Promise.resolve([]),
  ]);

  return (
    <div className="flex flex-col gap-6">
      <Breadcrumbs
        segments={[
          { label: "Memberships", href: "/memberships" },
          { label: "Invoices" },
        ]}
      />
      {sp.invoiceError ? (
        <FlashToast variant="error" message={sp.invoiceError} />
      ) : null}
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Invoices</h1>
          <p className="text-muted-foreground text-sm">
            {total} invoice{total === 1 ? "" : "s"} · recurring invoices are
            generated by the scheduler.
          </p>
        </div>
        {canEdit ? (
          <NewInvoiceSheet
            currency={currency}
            students={invoiceStudents}
            plans={invoicePlans}
          />
        ) : null}
      </div>

      <div className="flex flex-wrap items-center gap-3">
        <SearchInput placeholder="Search studentâ€¦" paramName="q" />
        <form className="w-40">
          {search ? <input type="hidden" name="q" value={search} /> : null}
          <AutoSubmitSelect
            name="status"
            defaultValue={sp.status ?? "ALL"}
            options={[
              { value: "ALL", label: "All statuses" },
              { value: "OPEN", label: "Open" },
              { value: "OVERDUE", label: "Overdue" },
              { value: "PAID", label: "Paid" },
              { value: "VOID", label: "Void" },
            ]}
          />
        </form>
      </div>

      {rows.length === 0 ? (
        <Card>
          <CardContent className="text-muted-foreground py-8 text-center text-sm">
            No invoices match these filters.
          </CardContent>
        </Card>
      ) : (
        <Card>
          <CardContent className="px-0">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead className="w-20">#</TableHead>
                  <TableHead>Student</TableHead>
                  <TableHead>Issued</TableHead>
                  <TableHead>Due</TableHead>
                  <TableHead>Status</TableHead>
                  <TableHead className="text-right">Total</TableHead>
                  <TableHead className="text-right">Balance</TableHead>
                </TableRow>
              </TableHeader>
              <TableBody>
                {rows.map((invoice) => (
                  <TableRow key={invoice.id}>
                    <TableCell className="font-mono text-xs">
                      <Link
                        href={`/memberships/invoices/${invoice.id}`}
                        className="hover:underline"
                      >
                        #{invoice.number}
                      </Link>
                    </TableCell>
                    <TableCell>
                      <Link
                        href={`/students/${invoice.student.id}`}
                        className="hover:underline"
                      >
                        {invoice.student.firstName} {invoice.student.lastName}
                      </Link>
                    </TableCell>
                    <TableCell>{formatDate(invoice.issueDate)}</TableCell>
                    <TableCell>{formatDate(invoice.dueDate)}</TableCell>
                    <TableCell>
                      {invoice.isOverdue ? (
                        <Badge variant="destructive">Overdue</Badge>
                      ) : (
                        <Badge variant={statusBadgeVariant(invoice.status)}>
                          {STATUS_LABELS[invoice.status] ?? invoice.status}
                        </Badge>
                      )}
                    </TableCell>
                    <TableCell className="text-right">
                      {formatMoney(invoice.financials.totalCents, currency)}
                    </TableCell>
                    <TableCell className="text-right">
                      {formatMoney(invoice.financials.balanceCents, currency)}
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </CardContent>
        </Card>
      )}

      <Pagination page={page} pageSize={25} totalCount={total} />
    </div>
  );
}
